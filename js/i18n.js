function t(key) {
  const lang = (window.S && S.settings && S.settings.lang) || 'en';
  return (STR[lang] && STR[lang][key]) || STR.en[key] || key;
}
/* pick a value from a {en, ms, zh} object, falling back to English */
function L(obj) {
  if (obj == null) return '';
  if (typeof obj === 'string') return obj;
  const lang = (window.S && S.settings && S.settings.lang) || 'en';
  return obj[lang] || obj.en || '';
}
